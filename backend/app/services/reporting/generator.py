from datetime import datetime, timezone
from typing import Dict, Any

class AssessmentReportGenerator:
    @staticmethod
    def generate_markdown_report(
        finding_data: Dict[str, Any],
        asset_data: Dict[str, Any],
        risk_data: Dict[str, Any],
        ai_data: Dict[str, Any]
    ) -> str:
        """
        Produces an auditable, executive-ready security assessment document.
        """
        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        cve = finding_data.get("cve_id", "UNKNOWN-CVE")
        host = asset_data.get("hostname", "unknown-host")
        priority = risk_data.get("priority_tier", "P2_MEDIUM")
        
        epss_val = finding_data.get("epss_score")
        epss_str = f"{epss_val * 100:.2f}%" if epss_val is not None else "N/A"
        kev_str = "YES (Active In-The-Wild Exploitation)" if finding_data.get("cisa_kev_listed") else "No"
        audit_str = "PASSED (0.0% Hallucinations)" if ai_data.get("citation_audit_passed") else "FAILED"

        lines = [
            f"# Security Assessment & Attack Narrative Report: {cve}",
            f"**Generated:** {now_str} | **VulnReason Version:** v1.0.0-prod",
            "",
            "## 1. Executive Summary",
            f"- **Target Asset:** `{host}` ({asset_data.get('exposure', 'INTERNAL')} tier)",
            f"- **Contextual Priority:** **{priority}**",
            f"- **Asset Criticality:** {asset_data.get('criticality', 'MEDIUM')}",
            f"- **CISA KEV Listed:** {kev_str}",
            f"- **FIRST EPSS Score:** {epss_str}",
            "",
            "## 2. Vulnerability & Component Provenance",
            f"- **Affected Component:** `{finding_data.get('package_name', 'System')}`",
            f"- **Installed Version:** `{finding_data.get('installed_version', 'unknown')}`",
            f"- **Fixed Release:** `{finding_data.get('fixed_version', 'unreleased')}`",
            f"- **Applicability Status:** {finding_data.get('applicability', 'INSUFFICIENT_EVIDENCE')}",
            f"- **Applicability Rationale:** {finding_data.get('applicability_rationale', 'N/A')}",
            "",
            "## 3. Deterministic Policy Evaluation",
            f"- **Applied Rules:** {', '.join(risk_data.get('applied_rules', []))}",
            "- **Reasoning Factors:**",
        ]

        for factor in risk_data.get("reasoning_factors", []):
            lines.append(f"  - {factor}")

        if risk_data.get("uncertainties"):
            lines.append("- **Identified Uncertainties:**")
            for u in risk_data.get("uncertainties", []):
                lines.append(f"  - ⚠️ {u}")

        lines.extend([
            "",
            "## 4. Structured AI Security Reasoning",
            f"- **Model Identifier:** `{ai_data.get('model_name', 'vulnreason-reasoning-engine-v1')}`",
            f"- **Citation Audit Status:** {audit_str}",
            f"- **Narrative Summary:** {ai_data.get('narrative_summary', 'No narrative generated.')}",
            "",
            "### Validated Claims & Prerequisites",
        ])

        for claim in ai_data.get("claims_payload", []):
            lines.append(f"- **[{claim.get('claim_type')}] {claim.get('claim_id')}:** {claim.get('statement')}")
            if claim.get("supporting_evidence_ids"):
                lines.append(f"  - *Evidence IDs:* `{', '.join(claim.get('supporting_evidence_ids'))}`")
            if claim.get("missing_verification"):
                lines.append(f"  - *Missing Evidence:* {', '.join(claim.get('missing_verification'))}")

        lines.extend([
            "",
            "## 5. Remediation Mandate & Verification Criteria",
            f"- **Recommended Action:** {risk_data.get('recommended_action', 'Apply vendor security patch.')}",
            "- **Verification Gate:** Finding closure requires cryptographic proof (SHA-256) or authenticated scanner rescan.",
            "",
            "---",
            "*Report generated by VulnReason. Unauthorized modifications invalidate evidence provenance.*"
        ])

        return "\n".join(lines)

report_generator = AssessmentReportGenerator()
